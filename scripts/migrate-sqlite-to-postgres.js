'use strict';

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');
const zlib = require('zlib');
const { DatabaseSync } = require('node:sqlite');
const { Client } = require('pg');

const root = path.resolve(__dirname, '..');
const sourcePath = path.resolve(process.env.SQLITE_SOURCE || path.join(root, 'data', 'ritapolis.db'));
const exportRoot = path.resolve(process.env.R2_EXPORT_DIR || path.join(root, 'data', 'r2-export'));
const manifestRoot = path.resolve(path.join(root, 'data', 'migration-manifests'));
const databaseUrl = process.env.DATABASE_URL_UNPOOLED || process.env.DATABASE_URL;
const reset = process.argv.includes('--reset');

if (!databaseUrl) {
  throw new Error('DATABASE_URL_UNPOOLED ou DATABASE_URL e obrigatoria');
}
if (!fs.existsSync(sourcePath)) {
  throw new Error(`SQLite de origem nao encontrado: ${sourcePath}`);
}

const EXCLUDED_TABLE_PATTERNS = [
  /^sqlite_/,
  /^documentos_fts(?:_|$)/,
  /^despesas_fts(?:_|$)/,
];

const OBJECT_COLUMNS = {
  documentos: [
    { source: 'texto_completo', prefix: 'texto', mime: 'text/plain; charset=utf-8' },
  ],
  documentos_anexos: [
    { source: 'texto_completo', prefix: 'texto', mime: 'text/plain; charset=utf-8' },
  ],
  transparencia_despesas: [
    { source: 'dados_extras', prefix: 'dados', mime: 'application/json' },
    { source: 'historico', prefix: 'historico', mime: 'application/json' },
  ],
  inteligencia_fatos: [
    { source: 'metadados_json', prefix: 'metadados', mime: 'application/json' },
  ],
};

function quoteIdentifier(value) {
  return `"${String(value).replaceAll('"', '""')}"`;
}

function pgType(sqliteType) {
  const type = String(sqliteType || '').toUpperCase();
  if (type.includes('INT')) { return 'BIGINT'; }
  if (type.includes('REAL') || type.includes('FLOA') || type.includes('DOUB')) { return 'DOUBLE PRECISION'; }
  if (type.includes('BLOB')) { return 'BYTEA'; }
  if (type.includes('BOOL')) { return 'BOOLEAN'; }
  return 'TEXT';
}

function pgDefault(value) {
  if (value === null || value === undefined) { return '' ; }
  const raw = String(value).trim();
  if (/^datetime\s*\(\s*['"]now['"]\s*\)$/i.test(raw)) { return ' DEFAULT CURRENT_TIMESTAMP'; }
  if (/^current_timestamp$/i.test(raw)) { return ' DEFAULT CURRENT_TIMESTAMP'; }
  if (/^[-+]?\d+(?:\.\d+)?$/.test(raw)) { return ` DEFAULT ${raw}`; }
  if (/^NULL$/i.test(raw)) { return ' DEFAULT NULL'; }
  if (/^'.*'$/.test(raw)) { return ` DEFAULT ${raw}`; }
  return '';
}

function tableInfo(sqlite, table) {
  return sqlite.prepare(`PRAGMA table_info(${quoteIdentifier(table)})`).all();
}

function tableSql(table, columns) {
  const primary = columns.filter((column) => column.pk).sort((a, b) => a.pk - b.pk);
  const definitions = columns.map((column) => {
    const isSingleIntegerPk = primary.length === 1 && primary[0].name === column.name && pgType(column.type) === 'BIGINT';
    const pieces = [quoteIdentifier(column.name)];
    pieces.push(isSingleIntegerPk ? 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : pgType(column.type));
    if (column.notnull) { pieces.push('NOT NULL'); }
    pieces.push(pgDefault(column.dflt_value));
    return pieces.filter(Boolean).join(' ');
  });
  if (primary.length > 1 || (primary.length === 1 && pgType(primary[0].type) !== 'BIGINT')) {
    definitions.push(`PRIMARY KEY (${primary.map((column) => quoteIdentifier(column.name)).join(', ')})`);
  }
  return `CREATE TABLE ${quoteIdentifier(table)} (\n  ${definitions.join(',\n  ')}\n)`;
}

function getTables(sqlite) {
  return sqlite.prepare("SELECT name FROM sqlite_master WHERE type = 'table' ORDER BY name").all()
    .map((row) => row.name)
    .filter((name) => !EXCLUDED_TABLE_PATTERNS.some((pattern) => pattern.test(name)));
}

function sha256(value) {
  return crypto.createHash('sha256').update(value).digest('hex');
}

function writeObject(value, mime, manifestObjects) {
  const body = Buffer.isBuffer(value) ? value : Buffer.from(String(value), 'utf8');
  const hash = sha256(body);
  const key = `objects/sha256/${hash.slice(0, 2)}/${hash}.gz`;
  const target = path.join(exportRoot, ...key.split('/'));
  if (!fs.existsSync(target)) {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, zlib.gzipSync(body, { level: 9 }));
  }
  manifestObjects.set(key, {
    key,
    sha256: hash,
    bytes: body.length,
    gzipBytes: fs.statSync(target).size,
    contentType: mime,
    contentEncoding: 'gzip',
  });
  return { key, hash, bytes: body.length };
}

function addObjectReferenceColumns(client, table, descriptors) {
  return Promise.all(descriptors.map(async ({ prefix }) => {
    await client.query(`ALTER TABLE ${quoteIdentifier(table)} ADD COLUMN IF NOT EXISTS ${quoteIdentifier(`${prefix}_objeto_key`)} TEXT`);
    await client.query(`ALTER TABLE ${quoteIdentifier(table)} ADD COLUMN IF NOT EXISTS ${quoteIdentifier(`${prefix}_objeto_sha256`)} TEXT`);
    await client.query(`ALTER TABLE ${quoteIdentifier(table)} ADD COLUMN IF NOT EXISTS ${quoteIdentifier(`${prefix}_objeto_bytes`)} BIGINT`);
  }));
}

function transformRow(table, row, manifestObjects) {
  const transformed = { ...row };
  for (const descriptor of OBJECT_COLUMNS[table] || []) {
    const value = transformed[descriptor.source];
    if (value === null || value === undefined || value === '') { continue; }
    const object = writeObject(value, descriptor.mime, manifestObjects);
    transformed[`${descriptor.prefix}_objeto_key`] = object.key;
    transformed[`${descriptor.prefix}_objeto_sha256`] = object.hash;
    transformed[`${descriptor.prefix}_objeto_bytes`] = object.bytes;
    if (table !== 'documentos') {
      transformed[descriptor.source] = null;
    }
  }
  return transformed;
}

async function insertBatch(client, table, rows) {
  if (!rows.length) { return; }
  // Object references are conditional: a row with an empty externalized field
  // does not have the corresponding columns. Build the batch column list from
  // every row so a sparse first row cannot silently discard later references.
  const columns = [...new Set(rows.flatMap((row) => Object.keys(row)))];
  const values = [];
  const tuples = rows.map((row) => {
    const placeholders = columns.map((column) => {
      values.push(Object.hasOwn(row, column) ? row[column] : null);
      return `$${values.length}`;
    });
    return `(${placeholders.join(', ')})`;
  });
  await client.query(
    `INSERT INTO ${quoteIdentifier(table)} (${columns.map(quoteIdentifier).join(', ')}) VALUES ${tuples.join(', ')}`,
    values
  );
}

async function copyTable(sqlite, client, table, manifestObjects) {
  const total = sqlite.prepare(`SELECT COUNT(*) AS total FROM ${quoteIdentifier(table)}`).get().total;
  const rows = sqlite.prepare(`SELECT * FROM ${quoteIdentifier(table)}`).iterate();
  const checksum = crypto.createHash('sha256');
  let batch = [];
  let copied = 0;
  await client.query('BEGIN');
  try {
    for (const sourceRow of rows) {
      checksum.update(JSON.stringify(sourceRow));
      const row = transformRow(table, sourceRow, manifestObjects);
      batch.push(row);
      if (batch.length >= 100) {
        await insertBatch(client, table, batch);
        copied += batch.length;
        batch = [];
      }
    }
    await insertBatch(client, table, batch);
    copied += batch.length;
    await client.query('COMMIT');
  } catch (error) {
    await client.query('ROLLBACK');
    throw error;
  }
  if (copied !== total) { throw new Error(`Contagem divergente em ${table}: ${copied}/${total}`); }
  return { table, rows: copied, sha256: checksum.digest('hex') };
}

async function createIndexes(sqlite, client, tables) {
  for (const table of tables) {
    const indexes = sqlite.prepare(`PRAGMA index_list(${quoteIdentifier(table)})`).all();
    for (const index of indexes) {
      if (index.origin === 'pk') { continue; }
      const columns = sqlite.prepare(`PRAGMA index_info(${quoteIdentifier(index.name)})`).all().map((item) => item.name).filter(Boolean);
      if (!columns.length) { continue; }
      const unique = index.unique ? 'UNIQUE ' : '';
      await client.query(`CREATE ${unique}INDEX IF NOT EXISTS ${quoteIdentifier(index.name)} ON ${quoteIdentifier(table)} (${columns.map(quoteIdentifier).join(', ')})`);
    }
  }
}

async function createForeignKeys(sqlite, client, tables) {
  for (const table of tables) {
    const foreignKeys = sqlite.prepare(`PRAGMA foreign_key_list(${quoteIdentifier(table)})`).all();
    const groups = new Map();
    for (const item of foreignKeys) {
      if (!groups.has(item.id)) { groups.set(item.id, []); }
      groups.get(item.id).push(item);
    }
    for (const [id, items] of groups) {
      items.sort((a, b) => a.seq - b.seq);
      const name = `fk_${table}_${id}`.slice(0, 63);
      const onDelete = ['CASCADE', 'RESTRICT', 'SET NULL', 'SET DEFAULT', 'NO ACTION'].includes(items[0].on_delete) ? items[0].on_delete : 'NO ACTION';
      const onUpdate = ['CASCADE', 'RESTRICT', 'SET NULL', 'SET DEFAULT', 'NO ACTION'].includes(items[0].on_update) ? items[0].on_update : 'NO ACTION';
      await client.query(`ALTER TABLE ${quoteIdentifier(table)} ADD CONSTRAINT ${quoteIdentifier(name)} FOREIGN KEY (${items.map((item) => quoteIdentifier(item.from)).join(', ')}) REFERENCES ${quoteIdentifier(items[0].table)} (${items.map((item) => quoteIdentifier(item.to)).join(', ')}) ON DELETE ${onDelete} ON UPDATE ${onUpdate} NOT VALID`);
      await client.query(`ALTER TABLE ${quoteIdentifier(table)} VALIDATE CONSTRAINT ${quoteIdentifier(name)}`);
    }
  }
}

async function resetSequences(client, tables, tableColumns) {
  for (const table of tables) {
    const primary = tableColumns.get(table).filter((column) => column.pk);
    if (primary.length !== 1 || pgType(primary[0].type) !== 'BIGINT') { continue; }
    const column = primary[0].name;
    await client.query(`SELECT setval(pg_get_serial_sequence($1, $2), COALESCE((SELECT MAX(${quoteIdentifier(column)}) FROM ${quoteIdentifier(table)}), 1), EXISTS(SELECT 1 FROM ${quoteIdentifier(table)}))`, [table, column]);
  }
}

async function createOperationalSchema(client) {
  await client.query(`
    CREATE TABLE IF NOT EXISTS schema_migrations (
      version TEXT PRIMARY KEY,
      applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      checksum TEXT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS pipeline_runs (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      job_type TEXT NOT NULL,
      status TEXT NOT NULL CHECK (status IN ('queued','running','succeeded','failed','deferred')),
      cursor_json JSONB,
      counters_json JSONB,
      error_summary TEXT,
      started_at TIMESTAMPTZ,
      finished_at TIMESTAMPTZ,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    CREATE INDEX IF NOT EXISTS idx_pipeline_runs_type_status ON pipeline_runs(job_type, status, created_at DESC);
    CREATE TABLE IF NOT EXISTS job_leases (
      job_type TEXT PRIMARY KEY,
      owner_id TEXT NOT NULL,
      lease_until TIMESTAMPTZ NOT NULL,
      updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    CREATE TABLE IF NOT EXISTS job_cursors (
      job_type TEXT PRIMARY KEY,
      cursor_json JSONB,
      next_run_at TIMESTAMPTZ,
      last_success_at TIMESTAMPTZ,
      updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
  `);
}

async function createSearchIndexes(client) {
  await client.query('CREATE EXTENSION IF NOT EXISTS unaccent');
  await client.query('ALTER TABLE documentos ADD COLUMN IF NOT EXISTS search_vector TSVECTOR');
  await client.query(`UPDATE documentos SET search_vector = to_tsvector('portuguese', unaccent(concat_ws(' ', titulo, resumo, texto_completo)))`);
  await client.query('CREATE INDEX IF NOT EXISTS idx_documentos_search_vector ON documentos USING GIN(search_vector)');
  await client.query('UPDATE documentos SET texto_completo = NULL WHERE texto_objeto_key IS NOT NULL');
  await client.query('ALTER TABLE transparencia_despesas ADD COLUMN IF NOT EXISTS search_vector TSVECTOR');
  await client.query(`UPDATE transparencia_despesas SET search_vector = to_tsvector('portuguese', unaccent(concat_ws(' ', credor_nome, historico, empenho, licitacao_ref)))`);
  await client.query('CREATE INDEX IF NOT EXISTS idx_despesas_search_vector ON transparencia_despesas USING GIN(search_vector)');
}

async function main() {
  fs.mkdirSync(exportRoot, { recursive: true });
  fs.mkdirSync(manifestRoot, { recursive: true });
  const sqlite = new DatabaseSync(sourcePath, { readOnly: true });
  const integrity = sqlite.prepare('PRAGMA integrity_check').all();
  if (integrity.some((row) => row.integrity_check !== 'ok')) {
    throw new Error(`SQLite invalido: ${JSON.stringify(integrity)}`);
  }
  const tables = getTables(sqlite);
  const tableColumns = new Map(tables.map((table) => [table, tableInfo(sqlite, table)]));
  const client = new Client({ connectionString: databaseUrl });
  const manifestObjects = new Map();
  const tableManifest = [];
  await client.connect();
  try {
    if (reset) {
      await client.query('DROP SCHEMA public CASCADE; CREATE SCHEMA public');
    }
    for (const table of tables) {
      await client.query(tableSql(table, tableColumns.get(table)));
      await addObjectReferenceColumns(client, table, OBJECT_COLUMNS[table] || []);
    }
    for (const table of tables) {
      tableManifest.push(await copyTable(sqlite, client, table, manifestObjects));
      process.stdout.write(`migrated ${table}\n`);
    }
    await createIndexes(sqlite, client, tables);
    await createForeignKeys(sqlite, client, tables);
    await resetSequences(client, tables, tableColumns);
    await createOperationalSchema(client);
    await createSearchIndexes(client);
    await client.query(
      `INSERT INTO schema_migrations(version, checksum) VALUES ($1, $2) ON CONFLICT (version) DO UPDATE SET checksum = EXCLUDED.checksum, applied_at = CURRENT_TIMESTAMP`,
      ['001-sqlite-baseline', sha256(JSON.stringify(tableManifest))]
    );
    const size = await client.query("SELECT pg_database_size(current_database()) AS bytes");
    const manifest = {
      version: 1,
      createdAt: new Date().toISOString(),
      source: sourcePath,
      sourceBytes: fs.statSync(sourcePath).size,
      sourceSha256: sha256(fs.readFileSync(sourcePath)),
      integrity,
      databaseBytes: Number(size.rows[0].bytes),
      tables: tableManifest,
      objects: [...manifestObjects.values()],
    };
    const target = path.join(manifestRoot, `migration-${Date.now()}.json`);
    fs.writeFileSync(target, `${JSON.stringify(manifest, null, 2)}\n`);
    process.stdout.write(`${JSON.stringify({ manifest: target, databaseBytes: manifest.databaseBytes, tables: tableManifest.length, objects: manifest.objects.length }, null, 2)}\n`);
  } finally {
    sqlite.close();
    await client.end();
  }
}

main().catch((error) => {
  console.error(error.stack || error.message);
  process.exitCode = 1;
});
